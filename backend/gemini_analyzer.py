class AbnormalMarker(BaseModel):
    """Structured representation of a single out-of-range biomarker."""

    test: str = Field(description="Name of the biomarker / test")
    value: str = Field(description="Observed numeric value with unit")
    status: Literal["Low", "High", "Borderline"] = Field(
        description="Severity classification relative to reference interval"
    )
    explanation: str = Field(
        description="Jargon-free explanation suitable for family members"
    )
    trend_note: str | None = Field(
        default=None,
        description="Historical delta comparison note if past records exist",
    )


class ReportSummary(BaseModel):
    """Complete structured medical report summary contract."""

    normal_summary: str = Field(
        description="Summary of tests within standard normal intervals"
    )
    abnormal: list[AbnormalMarker] = Field(
        default_factory=list,
        description="List of abnormal, borderline, or notable biomarkers",
    )
    cross_marker_patterns: list[str] = Field(
        default_factory=list,
        description="Physiological patterns observed across multiple markers",
    )
    urgency: UrgencyLevel = Field(description="Clinical urgency classification")
    specialist: str = Field(
        description="Primary medical specialty recommended for consult"
    )
    doctor_questions: list[str] = Field(
        min_length=3,
        max_length=3,
        description="Exactly three focused questions to ask the doctor",
    )
    disclaimer: str = Field(
        default="",
        description="Fixed statutory disclaimer injected in Python code",
    )


