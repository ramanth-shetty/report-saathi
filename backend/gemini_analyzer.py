# 4. Adversarial Jailbreak & Clinical Negligence Sanitizer
# ==============================================================================

_PROHIBITED_DIAGNOSES = re.compile(
    r"\b(?:diagnos(?:e|ed|is)\s+(?:with\s+)?(?:terminal|stage\s*[1-4]|cancer|adenocarcinoma|leukemia))\b",
    re.IGNORECASE,
)

_PROHIBITED_PRESCRIPTIONS = re.compile(
    r"\b(?:stop\s+taking|double\s+your\s+(?:dose|insulin)|increase\s+dose\s+to|"
    r"discontinue\s+medication|start\s+taking\s+\d+)\b",
    re.IGNORECASE,
)


def sanitize_adversarial_output(summary: ReportSummary) -> ReportSummary:
    """Enforces negative guardrails against adversarial injection attacks.

    Guarantees:
    - Never issues final cancer diagnoses or definitive terminal claims.
    - Never instructs altering, doubling, or stopping prescription medications.
    """

    def clean_text(text: str) -> str:
        if _PROHIBITED_DIAGNOSES.search(text):
            text = _PROHIBITED_DIAGNOSES.sub(
                "consult your doctor for medical evaluation of", text
            )
        if _PROHIBITED_PRESCRIPTIONS.search(text):
            text = _PROHIBITED_PRESCRIPTIONS.sub(
                "discuss your medication schedule directly with your doctor", text
            )
        return text

    summary.normal_summary = clean_text(summary.normal_summary)
    summary.specialist = clean_text(summary.specialist)

    for marker in summary.abnormal:
        marker.explanation = clean_text(marker.explanation)
        if marker.trend_note:
            marker.trend_note = clean_text(marker.trend_note)

    summary.cross_marker_patterns = [
        clean_text(pat) for pat in summary.cross_marker_patterns
    ]
    summary.doctor_questions = [clean_text(q) for q in summary.doctor_questions[:3]]

    return summary


