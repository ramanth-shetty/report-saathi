# 3. Unit Normalization & Safety Overrides Engine
# ==============================================================================


def normalize_biomarker_unit(
    test_name: str, value: float, unit: str
) -> tuple[float, str]:
    """Normalizes biomarker numeric values to canonical clinical units."""
    clean_test = test_name.lower().strip()
    clean_unit = unit.lower().strip()

    # Glucose: mmol/L -> mg/dL (multiply by 18.0)
    if any(k in clean_test for k in ["glucose", "sugar", "fbs", "rbs", "ppbs"]):
        if clean_unit in ["mmol/l", "mmol"]:
            return (round(value * 18.0, 2), "mg/dL")

    # Hemoglobin: g/L -> g/dL (divide by 10.0)
    if any(k in clean_test for k in ["hemoglobin", "haemoglobin", "hb"]):
        if clean_unit in ["g/l"]:
            return (round(value / 10.0, 2), "g/dL")

    # Platelets: lakhs/cumm -> /cumm (multiply by 100,000)
    if "platelet" in clean_test:
        if "lakh" in clean_unit:
            return (round(value * 100000.0, 2), "/cumm")
        if clean_unit in ["/ul", "cells/mcl", "k/ul", "10^3/ul", "thou/ul"]:
            if clean_unit in ["k/ul", "10^3/ul", "thou/ul"] or value < 1000:
                return (round(value * 1000.0, 2), "/cumm")
            return (value, "/cumm")

    return (value, unit)


def _match_alias(test_name: str, aliases: list[str]) -> bool:
    """Check if test_name matches any known alias."""
    clean_name = test_name.lower()
    for alias in aliases:
        if re.search(rf"\b{re.escape(alias)}\b", clean_name):
            return True
    return False


def _normalize_lang(lang: str) -> SupportedLanguage:
    """Safely validate and narrow vernacular language codes."""
    if lang == "hi":
        return "hi"
    if lang == "kn":
        return "kn"
    return "en"


def apply_safety_overrides(
    parsed_rows: list[dict[str, Any]],
    summary: ReportSummary,
    lang: str = "en",
) -> ReportSummary:
    """Evaluates parsed biomarker values against deterministic CRITICAL_RULES.

    Invariants:
    1. Urgency can only escalate (Routine -> Consult Soon -> Prompt Attention).
    2. Any critical rule match forces urgency = 'Prompt Attention'.
    3. Prominent non-AI clinical directives are prepended to explanations.
    4. Exact immutable disclaimer is always attached.
    """
    selected_lang = _normalize_lang(lang)
    suffix = ALERT_SUFFIX.get(selected_lang, ALERT_SUFFIX["en"])

    # Determine starting urgency rank
    current_rank = URGENCY_RANKS.get(summary.urgency, 1)
    max_rank = current_rank

    triggered_overrides: list[tuple[str, str, float, str, str]] = []

    for row in parsed_rows:
        raw_name = str(row.get("test_name", ""))
        try:
            raw_val = float(row.get("observed_value", 0.0))
        except (ValueError, TypeError):
            continue
        raw_unit = str(row.get("unit", ""))

        norm_val, norm_unit = normalize_biomarker_unit(raw_name, raw_val, raw_unit)

        for aliases, _expected_unit, op, threshold, label in CRITICAL_RULES:
            if not _match_alias(raw_name, aliases):
                continue

            # Evaluate threshold condition
            is_critical = False
            if op == "<" and norm_val < threshold:
                is_critical = True
            elif op == ">" and norm_val > threshold:
                is_critical = True

            if is_critical:
                triggered_overrides.append((raw_name, op, norm_val, norm_unit, label))
                max_rank = max(max_rank, URGENCY_RANKS["Prompt Attention"])

    # Enforce directional urgency
    summary.urgency = RANK_TO_URGENCY[max_rank]

    # Prepend critical warning directives to abnormal marker explanations
    for (
        crit_name,
        crit_op,
        crit_val,
        crit_unit,
        crit_label,
    ) in triggered_overrides:
        directive = f"{crit_label} - {suffix}"
        matched_marker: AbnormalMarker | None = None

        for marker in summary.abnormal:
            if _match_alias(marker.test, [crit_name.lower()]) or any(
                _match_alias(marker.test, r[0])
                for r in CRITICAL_RULES
                if r[4] == crit_label
            ):
                matched_marker = marker
                break

        if matched_marker is not None:
            if directive not in matched_marker.explanation:
                matched_marker.explanation = (
                    f"{directive} {matched_marker.explanation}".strip()
                )
            matched_marker.status = "Low" if crit_op == "<" else "High"
        else:
            summary.abnormal.insert(
                0,
                AbnormalMarker(
                    test=crit_name,
                    value=f"{crit_val} {crit_unit}".strip(),
                    status="Low" if crit_op == "<" else "High",
                    explanation=directive,
                ),
            )

        # Enhance doctor questions for acute management if critical
        if "Glucose" in crit_label:
            summary.doctor_questions[0] = (
                "What immediate evaluation or acute steps are needed to manage "
                "these critically high blood sugar levels safely?"
            )
        elif "Hemoglobin" in crit_label or "Anemia" in crit_label:
            summary.doctor_questions[0] = (
                "Does my critically low hemoglobin level require urgent medical "
                "interventions or blood transfusion evaluation?"
            )
        elif "Platelet" in crit_label:
            summary.doctor_questions[0] = (
                "What immediate precautions and urgent clinical monitoring are "
                "required for this critically low platelet count?"
            )

    # Invariant: Disclaimers are always injected in code
    summary.disclaimer = DISCLAIMER.get(selected_lang, DISCLAIMER["en"])

    # Adversarial post-processing filter
    summary = sanitize_adversarial_output(summary)

    return summary


